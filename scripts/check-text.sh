#!/bin/sh

set -e

FILE="$1"

if [ -z "$FILE" ]; then
  echo "Usage: check <file>"
  exit 1
fi

if [ ! -f "$FILE" ]; then
  echo "File not found: $FILE"
  exit 1
fi

opencode run "Проверь файл '$FILE' на орфографические, пунктуационные и грамматические ошибки русского языка и исправь их непосредственно в файле. Также проверь верность Markdown-разметки: цитаты должны быть выделены с тегом >, код и так далее. Не меняй стиль, смысл, структуру текста и авторскую лексику. Исправляй только явные ошибки."